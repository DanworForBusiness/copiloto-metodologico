const fs=require('fs'),vm=require('vm'),assert=require('assert/strict'),path=require('path');
const sandbox={window:{},Set};
vm.runInNewContext(fs.readFileSync(path.resolve(__dirname,'../../webapp/static/table_selection.js'),'utf8'),sandbox);
const memory={data:{},getItem(k){return this.data[k]},setItem(k,v){this.data[k]=v}};
const api=sandbox.window.dwTableSelection;
const opts=key=>({key,idPattern:/^[1-9][0-9]*$/,max:Number.MAX_SAFE_INTEGER});
const a=api.createStore(memory,opts('operations:user-a:list-one'));
const b=api.createStore(memory,opts('operations:user-b:list-one'));
const c=api.createStore(memory,opts('cchh:user-a:list-one'));
a.add(['1','2','1','01','bad']);
assert.equal(JSON.stringify(a.ids()),'["1","2"]');
assert.equal(b.size(),0);assert.equal(c.size(),0);
const restored=api.createStore(memory,opts('operations:user-a:list-one'));
assert.equal(JSON.stringify(restored.ids()),'["1","2"]');
const row={classList:{values:new Set(),add(x){this.values.add(x)},remove(x){this.values.delete(x)}}};
const box=id=>({checked:false,getAttribute:()=>id,closest:()=>row});
const boxes=[box('1'),box('3')],head={};
const doc={querySelectorAll:s=>s==='rows'?boxes:[head]};
api.syncRows(doc,restored,{row:'rows',page:'heads',attribute:'id'});
assert.equal(head.indeterminate,true);assert.equal(head.checked,false);
assert.equal(boxes[0].checked,true);assert.equal(boxes[1].checked,false);
restored.reconcile(['2','3']);
assert.equal(JSON.stringify(restored.ids()),'["2"]');
restored.clear();assert.equal(restored.size(),0);
assert(!Object.values(memory.data).join('').includes('token'));
console.log('Shared selection scope, persistence, reconciliation and indeterminate state: OK');
